function enrichItem(
  item: Omit<ProducaoPorProcedimento, 'coGrupo' | 'noGrupo' | 'coSubGrupo' | 'noSubGrupo' | 'vlUnitario' | 'vlrPactuado' | 'saldoFinanceiro' | 'percExecucaoFinanceira'> & {
    coGrupo?: string;
    noGrupo?: string;
    coSubGrupo?: string;
    noSubGrupo?: string;
    vlUnitario?: number;
    vlrPactuado?: number | null;
    saldoFinanceiro?: number;
    percExecucaoFinanceira?: number | null;
  }
): ProducaoPorProcedimento {
  const meta = SIGTAP_METADATA[item.coProcedimento] || {
    coGrupo: item.coProcedimento.substring(0, 2),
    noGrupo: item.coProcedimento.startsWith('02') ? 'PROCEDIMENTOS COM FINALIDADE DIAGNÓSTICA' : item.coProcedimento.startsWith('03') ? 'PROCEDIMENTOS CLÍNICOS' : 'PROCEDIMENTOS CIRÚRGICOS',
    coSubGrupo: item.coProcedimento.substring(2, 4),
    noSubGrupo: 'OUTROS SUBGRUPOS',
    vlUnitario: item.qtdAprovada > 0 ? Math.round((item.vlrAprovado / item.qtdAprovada) * 100) / 100 : 10.00,
  };

  const coGrupo = item.coGrupo || meta.coGrupo;
  const noGrupo = item.noGrupo || meta.noGrupo;
  const coSubGrupo = item.coSubGrupo || meta.coSubGrupo;
  const noSubGrupo = item.noSubGrupo || meta.noSubGrupo;
  const vlUnitario = item.vlUnitario !== undefined ? item.vlUnitario : meta.vlUnitario;

  const vlrPactuado = item.vlrPactuado !== undefined ? item.vlrPactuado : (
    item.qtdPactuadaMensal !== null ? Math.round(item.qtdPactuadaMensal * vlUnitario * 100) / 100 : null
  );

  const saldoFinanceiro = item.saldoFinanceiro !== undefined ? item.saldoFinanceiro : (
    vlrPactuado !== null ? Math.round((item.vlrAprovado - vlrPactuado) * 100) / 100 : item.vlrAprovado
  );

  const percExecucaoFinanceira = item.percExecucaoFinanceira !== undefined ? item.percExecucaoFinanceira : (
    vlrPactuado && vlrPactuado > 0 ? Math.round((item.vlrAprovado / vlrPactuado) * 10000) / 100 : null
  );

  return {
    ...item,
    coGrupo,
    noGrupo,
    coSubGrupo,
    noSubGrupo,
    vlUnitario,
    vlrPactuado,
    saldoFinanceiro,
    percExecucaoFinanceira,
  };
}

